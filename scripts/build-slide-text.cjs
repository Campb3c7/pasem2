#!/usr/bin/env node
/* Builds data/slide-text-<lecture>.js from source-material/<course>/text/<lecture>.md: every slide's text,
   verbatim, as HTML lists/tables (the Slide-by-slide study mode shows it under the slide picture).
   Usage: node scripts/build-slide-text.cjs cardio-part-3 cad-part-1 */
const fs = require("fs");
const path = require("path");
const [course, lecture] = process.argv.slice(2);
if (!course || !lecture) { console.error("usage: build-slide-text.cjs <course> <lecture>"); process.exit(1); }
const root = path.join(__dirname, "..");
const md = fs.readFileSync(path.join(root, "source-material", course, "text", lecture + ".md"), "utf8");
const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
const out = {};
md.split(/^## Slide (\d+)\s*$/m).slice(1).forEach((chunk, i, arr) => {
  if (i % 2) return;
  const n = Number(chunk), body = arr[i + 1];
  const items = []; const rows = []; const seen = new Set();
  body.split("\n").forEach((line) => {
    if (/^\s*\|/.test(line)) { rows.push(line.trim().replace(/^\||\|$/g, "").split("|").map((c) => esc(c.trim()))); return; }
    const m = line.match(/^(\s*)- (.*)$/);
    if (!m) return;
    const text = m[2].trim();
    if (!text || text === "[picture]" || /^\d{1,3}$/.test(text)) return;
    if (/^Coronary Artery Disease 20\d\d, Part/.test(text)) { if (seen.has(text)) return; seen.add(text); }
    items.push({ lvl: Math.floor(m[1].length / 2), text: esc(text) });
  });
  let html = "", depth = -1;
  items.forEach((it) => {
    const lvl = Math.min(it.lvl, depth + 1);
    if (lvl > depth) { html += "<ul>"; depth += 1; }
    else { html += "</li>"; while (depth > lvl) { html += "</ul></li>"; depth -= 1; } }
    html += "<li>" + it.text;
  });
  if (depth >= 0) { html += "</li>"; while (depth > 0) { html += "</ul></li>"; depth -= 1; } html += "</ul>"; }
  if (rows.length) html += '<table class="ss-table">' + rows.map((r) => "<tr>" + r.map((c) => "<td>" + c + "</td>").join("") + "</tr>").join("") + "</table>";
  out[n] = html;
});
const file = path.join(root, "data", "slide-text-" + lecture + ".js");
fs.writeFileSync(file, "/* Generated by scripts/build-slide-text.cjs from source-material/" + course + "/text/" + lecture + ".md: do not edit by hand. */\n" +
  "window.SLIDE_TEXT = window.SLIDE_TEXT || {};\nwindow.SLIDE_TEXT[" + JSON.stringify(lecture) + "] = " + JSON.stringify(out, null, 0).replace(/,"(\d+)":/g, ',\n"$1":') + ";\n");
console.log("wrote", file, Object.keys(out).length, "slides");
